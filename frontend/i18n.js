/* Tiny i18n runtime shared by every page. */
window.DXMAP_I18N_RUNTIME = (function(){
  const LANGS = window.DXMAP_I18N;
  const KEY = 'dxmap_lang';
  function detect(){
    const saved = localStorage.getItem(KEY);
    if (saved && LANGS[saved]) return saved;
    const nav = (navigator.language || 'en').slice(0,2);
    return LANGS[nav] ? nav : 'en';
  }
  let current = detect();
  function t(key, vars){
    let s = (LANGS[current].t[key] ?? LANGS.en.t[key] ?? key);
    if (vars) for (const k in vars) s = s.replace('{'+k+'}', vars[k]);
    return s;
  }
  function apply(root){
    root = root || document;
    document.documentElement.lang = current;
    document.documentElement.dir = LANGS[current].dir;
    root.querySelectorAll('[data-i18n]').forEach(el=>{
      el.textContent = t(el.getAttribute('data-i18n'));
    });
    root.querySelectorAll('[data-i18n-html]').forEach(el=>{
      el.innerHTML = t(el.getAttribute('data-i18n-html'));
    });
    root.querySelectorAll('[data-i18n-placeholder]').forEach(el=>{
      el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
    });
    root.querySelectorAll('[data-i18n-title]').forEach(el=>{
      el.title = t(el.getAttribute('data-i18n-title'));
    });
  }
  function setLang(lang){
    if (!LANGS[lang]) return;
    current = lang;
    localStorage.setItem(KEY, lang);
    apply();
    document.dispatchEvent(new CustomEvent('dxmap:lang', {detail:{lang}}));
  }
  return { t, apply, setLang, get current(){ return current; }, langs: Object.keys(LANGS) };
})();
